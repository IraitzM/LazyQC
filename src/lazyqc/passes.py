"""Observable cone analysis for unitary, product-input circuits.

`cone_indices` follows supports only. `commuting_cone` also tracks which Pauli letters can
reach each wire and drops gates that leave every such operator unchanged. Both depend on
gate names and wires, never on angles, so programs sharing a topology share the result.
"""

from .ir import Gate, Pauli

# A Pauli letter is a pair of bits (x, z): X = (1, 0), Z = (0, 1), Y = (1, 1). Letter sets
# are bit masks, and a wire that is not live has the empty mask (only the identity).
_LETTER_MASK = {"X": 1, "Y": 2, "Z": 4}
_MASK_BITS = {1: (1, 0), 2: (1, 1), 4: (0, 1)}
_BITS_MASK = {bits: mask for mask, bits in _MASK_BITS.items()}
_ALL = 7
_GENERATORS = {"RX": (1, 0), "RY": (1, 1), "RZ": (0, 1)}
_PAULI_GATES = {"X": (1, 0), "Y": (1, 1), "Z": (0, 1)}


def _strings(mask):
    """Return the bit pairs a letter set allows, including the identity."""
    return [(0, 0)] + [bits for m, bits in _MASK_BITS.items() if mask & m]


def _mask(strings):
    """Return the letter set of the non-identity bit pairs in `strings`."""
    return sum(_BITS_MASK[bits] for bits in set(strings) if bits != (0, 0))


def _anticommutes(a, b):
    """Return whether two single-qubit Pauli strings anticommute."""
    return (a[0] & b[1]) ^ (a[1] & b[0]) == 1


def _one_qubit(name, mask):
    """Return ``(unchanged, letters)`` for conjugating by a single-qubit gate."""
    strings = _strings(mask)
    if name == "H":
        return mask == 0, _mask([(z, x) for x, z in strings])
    if name in _PAULI_GATES:  # a sign flip changes the operator but not its letters
        return all(not _anticommutes(p, _PAULI_GATES[name]) for p in strings), mask
    axis = _GENERATORS[name]
    out = []
    for p in strings:
        out.append(p)
        if _anticommutes(p, axis):  # R P R^dagger = cos P + sin (P times the axis)
            out.append((p[0] ^ axis[0], p[1] ^ axis[1]))
    return all(not _anticommutes(p, axis) for p in strings), _mask(out)


def _two_qubit(name, mask_a, mask_b):
    """Return ``(unchanged, letters_a, letters_b)`` for conjugating by a two-qubit gate."""
    unchanged, out_a, out_b = True, [], []
    for pa in _strings(mask_a):
        for pb in _strings(mask_b):
            if name == "CX":  # control a, target b
                images = [(pa[0], pa[1] ^ pb[1]), (pb[0] ^ pa[0], pb[1])]
                fixed = images == [pa, pb]
            elif name == "CZ":
                images = [(pa[0], pa[1] ^ pb[0]), (pb[0], pb[1] ^ pa[0])]
                fixed = images == [pa, pb]
            else:  # RZZ, generated by Z Z
                images = [pa, pb]
                fixed = (pa[0] ^ pb[0]) == 0
                if not fixed:
                    out_a.append((pa[0], pa[1] ^ 1))
                    out_b.append((pb[0], pb[1] ^ 1))
            unchanged &= fixed
            out_a.append(images[0])
            out_b.append(images[1])
    return unchanged, _mask(out_a), _mask(out_b)


_ONE = {
    name: {m: _one_qubit(name, m) for m in range(8)}
    for name in ("H", "X", "Y", "Z", "RX", "RY", "RZ")
}
_TWO = {
    name: {(a, b): _two_qubit(name, a, b) for a in range(8) for b in range(8)}
    for name in ("CX", "CZ", "RZZ")
}


def commuting_cone(shape_ops, factors):
    """Return live wires and retained operation indices for a commutation-aware cone.

    `shape_ops` holds ``(gate name, wires)`` per operation and `factors` the observable's
    ``(wire, letter)`` pairs. Going backwards, each wire keeps the set of Pauli letters its
    part of the operator can carry. A gate that acts as the identity on every operator those
    sets allow (a CX whose control carries only Z, an RZ on a wire carrying only Z) is
    dropped. Any other gate is kept and the letter sets of its wires are widened to what it
    can produce, so the result is exact and still a function of structure only.
    """
    letters = {q: _LETTER_MASK[p] for q, p in factors if p != "I"}
    live = set(letters)
    retained = []
    for index in range(len(shape_ops) - 1, -1, -1):
        name, qubits = shape_ops[index]
        if len(qubits) == 1:
            (a,) = qubits
            mask = letters.get(a, 0)
            if not mask:
                continue
            table = _ONE.get(name)
            if table is None:
                letters[a] = _ALL
            else:
                unchanged, letters[a] = table[mask]
                if unchanged:
                    continue
        else:
            a, b = qubits
            masks = (letters.get(a, 0), letters.get(b, 0))
            if not any(masks):
                continue
            table = _TWO.get(name)
            if table is None:
                letters[a] = letters[b] = _ALL
            else:
                unchanged, letters[a], letters[b] = table[masks]
                if unchanged:
                    continue
        live.update(qubits)
        retained.append(index)
    return tuple(sorted(live)), tuple(reversed(retained))


def cone_indices(qubits: tuple[tuple[int, ...], ...], support):
    """Return live wires and retained operation indices for a backward support cone.

    Only gate wires matter, so programs sharing a topology share the result.
    """
    live = set(support)
    retained = []
    for index in range(len(qubits) - 1, -1, -1):
        if live.intersection(qubits[index]):
            live.update(qubits[index])
            retained.append(index)
    return tuple(sorted(live)), tuple(reversed(retained))


def causal_cone(operations: tuple[Gate, ...], observable: Pauli):
    """Extract the conservative backward causal cone for a Pauli observable."""
    wires, retained = cone_indices(
        tuple(g.qubits for g in operations), (q for q, _ in observable.factors)
    )
    return wires, tuple(operations[i] for i in retained)
