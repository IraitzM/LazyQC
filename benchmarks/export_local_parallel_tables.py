#!/usr/bin/env python3
"""Export IEEE appendix tables directly from the checked local study aggregate."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def span(values, digits=2):
    return f"{min(values):.{digits}f}--{max(values):.{digits}f}"


def main():
    data = json.loads((ROOT / "results/local_parallel/summary.json").read_text())
    labels = {
        "tiny_4q": "4q, 4 layers",
        "medium_10q": "10q, 20 layers",
        "balanced_14q_2tasks": "14q, 40 layers",
        "balanced_14q_4tasks": "14q, 40 layers",
        "balanced_14q_8tasks": "14q, 40 layers",
        "wide_16q": "16q, 40 layers",
        "shallow_14q": "14q, 4 layers",
        "deep_14q": "14q, 80 layers",
        "imbalanced_14q": "14q, uneven depths",
        "bridge_cut_8q": "8q cut fragments",
    }
    text = r"""% Generated by benchmarks/export_local_parallel_tables.py; do not hand-edit rows.
\subsection{Expanded Local Multiprocessing Artifacts}
The expanded study uses \path{benchmarks/run_local_parallel.py} with nine repetitions and
session indices zero through two. Raw data, plans, reference values, process samples, and source
fingerprints are in \path{results/local_parallel/session0/} through
\path{results/local_parallel/session2/}. The checked aggregate is
\path{results/local_parallel/summary.json}; its generator verifies source and graph
fingerprints. Workloads are fixed across sessions. Full calibration is charged to each workload
when calculating a standalone ten-call lifetime, although the measurement runner performs
calibration once per session. First-call and warm measurements are interleaved with controls;
unmeasured gaps are excluded from the summed cost model.

Table~\ref{tab:local_parallel_full} retains all ten workloads. $T_1$ and $T_4$ are ranges of
configuration-level median collection times. $S_2$ and $S_4$ are ranges of paired geometric-mean
speedups against serial controls measured within the corresponding pool configuration. $L_4$
includes common construction, planning, and calibration, plus parallel warmup, ten collections,
and shutdown. Bootstrap intervals for the nine paired trials in each session are retained in the
JSON, rather than conflated with session ranges. Three sessions on one host do not establish
between-machine uncertainty.

\begin{table*}[!t]
\caption{All Local Multiprocessing Workloads: Warm Timings, Paired Speedups, and Ten-Call
Setup-Charged Speedups. Ranges Span Three Sessions.}
\label{tab:local_parallel_full}
\centering
\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrrr}
\toprule
Workload & Tasks & $T_1$ (ms) & $T_4$ (ms) & $S_2$ & $S_4$ & $S_4/4$ & $L_4$ \\
\midrule
"""
    for case in data["cases"]:
        configs = case["configurations"]
        two, four = configs["w2_m2"], configs["w4_m4"]
        row = [
            labels[case["name"]],
            str(case["unique_tasks"]),
            span([c["modes"]["serial"]["median_ns"] / 1e6 for c in configs["w1_m1"]]),
            span([c["modes"]["parallel"]["median_ns"] / 1e6 for c in four]),
            span([c["paired_speedups"]["parallel"]["geomean"] for c in two]),
            span([c["paired_speedups"]["parallel"]["geomean"] for c in four]),
            span([c["paired_speedups"]["parallel"]["geomean"] / 4 for c in four]),
            span([c["lifetime"]["final_speedup"] for c in four]),
        ]
        text += " & ".join(row) + r" \\" + "\n"
    text += r"""\bottomrule
\end{tabular}
\par\vspace{8pt}
\caption{Resource Diagnostics for Eight 16-Qubit Tasks. Each State Occupies 1 MiB; Values Span
Three Separate Profiling Collections, One per Session.}
\label{tab:local_parallel_resources}
\centering
\footnotesize
\setlength{\tabcolsep}{5pt}
\begin{tabular}{rrrrrr}
\toprule
Workers & Payload cap (MiB) & Warm time (ms) & Sampled RSS sum (MiB) & CPU-s & Mean cores \\
\midrule
"""
    wide = next(c for c in data["cases"] if c["name"] == "wide_16q")
    for key in ("w1_m1", "w2_m2", "w4_m1", "w4_m2", "w4_m4"):
        configs = wide["configurations"][key]
        first = configs[0]
        mode = "serial" if first["workers"] == 1 else "parallel"
        row = [
            str(first["workers"]),
            str(first["payload_slots"]),
            span([c["modes"][mode]["median_ns"] / 1e6 for c in configs]),
            span([c["sampled_peak_sum_rss_bytes"] / 2**20 for c in configs], 1),
            span([c["resource_probe_cpu_ns"] / 1e9 for c in configs]),
            span([c["resource_probe_core_equivalents"] for c in configs]),
        ]
        text += " & ".join(row) + r" \\" + "\n"
    text += r"""\bottomrule
\end{tabular}
\end{table*}

The uneven case contains seven four-layer components and one 80-layer component. Other uncut
rows use the same depth per component. The cut row joins two eight-qubit, 20-layer components
with a CX bridge and adds terminal rotations. Scalar observables are validated using an
independent NumPy implementation; no sampled quantum execution is involved.

Warm timings in Table~\ref{tab:local_parallel_resources} come from unprofiled trials. RSS and
CPU columns come from separate instrumented collections. RSS is the sampled sum over the parent
and the active pool, including shared-page double counting and retained runtime allocations.
CPU-s sums user and system process counters; mean cores divides that CPU time by profiled
collection wall time and includes sampler/parent overhead. Raw process counters have 10 ms
resolution. All reported resource probes in this table exceed 100 ms; shorter workloads retain
raw counters but suppress derived utilization ratios. These measurements do not bound peak RSS
or measure energy.
"""
    (ROOT / "paper/sections/10_local_parallel_appendix.tex").write_text(text)


if __name__ == "__main__":
    main()
