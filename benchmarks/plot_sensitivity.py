"""Publication plots and IEEE appendix table from validated summary artifacts."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "results/sensitivity"


def main():
    summary = json.loads((BASE / "summary.json").read_text())
    raw = json.loads((BASE / "session0/evaluation.json").read_text())
    plt.rcParams.update(
        {"font.size": 8, "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42}
    )
    fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.8), layout="constrained")
    actual = np.array([a for r in raw["accuracy"]["random"] for a in r["actual"]])
    bounds = np.array([b for r in raw["accuracy"]["random"] for b in r["bound"]])
    nonzero = (actual > 0) & (bounds > 0)
    axes[0].scatter(bounds[nonzero], actual[nonzero], s=7, alpha=0.4, color="#266b8a")
    axes[0].plot([1e-14, 3], [1e-14, 3], "--", color="#b34237", lw=1, label="Error = bound")
    axes[0].set(
        xscale="log",
        yscale="log",
        xlabel="Conditional absolute-error bound",
        ylabel="Observed absolute error",
        title="(a) Simultaneous perturbations",
        xlim=(1e-14, 3),
        ylim=(1e-14, 3),
    )
    axes[0].legend(frameon=False, fontsize=7, loc="upper left")
    names = ["bridge_8q_2b", "bridge_12q_2b", "bridge_16q_2b", "bridge_15q_3b", "control_16q_2b"]
    for j, (workers, color) in enumerate(
        zip((1, 2, 4), ("#266b8a", "#d09432", "#7c588c"), strict=True)
    ):
        rows = [
            next(r for r in summary["families"] if r["name"] == name and r["workers"] == workers)
            for name in names
        ]
        medians = np.array([r["lifetime_median"] for r in rows])
        low = medians - np.array([r["lifetime_speedup"][0] for r in rows])
        high = np.array([r["lifetime_speedup"][1] for r in rows]) - medians
        axes[1].bar(
            np.arange(len(names)) + (j - 1) * 0.24,
            medians,
            width=0.22,
            color=color,
            label=f"{workers} worker{'s' if workers > 1 else ''}",
            yerr=[low, high],
            capsize=2,
            error_kw={"linewidth": 0.7},
        )
    axes[1].axhline(1, color="#b34237", linestyle="--", lw=1)
    axes[1].set(
        xticks=range(len(names)),
        xticklabels=["8q", "12q", "16q", "15q", "16q\ncontrol"],
        ylabel="Exact / approximate total time",
        title="(b) Eight collections, all setup charged",
    )
    axes[1].legend(frameon=False, fontsize=7, loc="upper left")
    for ax in axes:
        ax.grid(axis="y", alpha=0.15)
    for extension in ("pdf", "png"):
        fig.savefig(ROOT / f"paper/figures/sensitivity_tradeoff.{extension}", dpi=200)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(4.6, 2.6), layout="constrained")
    rows = summary["finite_difference"]
    ax.loglog(
        [r["step"] for r in rows],
        [r["absolute_error"] for r in rows],
        "o-",
        label="Central difference",
    )
    ax.axhline(summary["parameter_shift_error"], color="#d09432", label="Parameter shift")
    ax.set(
        xlabel="Finite-difference step (radians)",
        ylabel="Absolute derivative error",
        title=r"Single-qubit $\langle Z\rangle=\cos(0.37)$",
    )
    ax.legend(frameon=False, fontsize=8)
    for extension in ("pdf", "png"):
        fig.savefig(ROOT / f"paper/figures/sensitivity_precision.{extension}", dpi=200)
    plt.close(fig)

    def span(values):
        return f"{values[0]:.2f}--{values[1]:.2f}"

    lines = [
        r"% Generated by benchmarks/plot_sensitivity.py from validated summary.json.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Sensitivity study: ranges across three interpreter sessions "
        r"and the stated seeds. "
        r"Warm speedups compare exact and bounded execution at equal worker counts. "
        r"Lifetime charges eight collections, profiling, search and pool setup/shutdown. "
        r"Payload is the largest individual complex128 state, not RSS. Budget: $0.01$ per output.}",
        r"\label{tab:sensitivity-results}",
        r"\footnotesize",
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r"Fixture & Seeds & Workers & Width & Payload factor & Warm speedup & "
        r"Lifetime speedup & Profile (ms) \\",
        r"\midrule",
    ]
    labels = {
        "bridge_8q_2b": "8q / 2 blocks",
        "bridge_12q_2b": "12q / 2 blocks",
        "bridge_16q_2b": "16q / 2 blocks",
        "bridge_15q_3b": "15q / 3 blocks",
        "control_16q_2b": "16q connected control",
    }
    for row in summary["families"]:
        lines.append(
            f"{labels[row['name']]} & {row['independent_seeds']} & {row['workers']} & "
            f"${row['exact_width'][0]}\\to {row['bounded_width'][0]}$ & "
            f"{row['payload_reduction'][0]:.0f} & {span(row['warm_speedup'])} & "
            f"{span(row['lifetime_speedup'])} & {span(row['profile_ms'])} " + r"\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    (ROOT / "paper/sections/14_sensitivity_tables.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
